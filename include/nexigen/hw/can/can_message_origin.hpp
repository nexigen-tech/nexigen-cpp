#pragma once

#include <array>
#include <cstdint>
#include <format>
#include <string_view>

#include <nlohmann/json.hpp>

#include <nexigen/core/enum_traits.hpp>
#include <nexigen/core/serialization_mandate.hpp>

namespace nexigen::hw::can {

/// @brief Whether a message was initiated locally or by an external device.
enum class CanMessageOrigin : std::uint8_t {
    ExternalDevice, ///< Generated by another device on the bus.
    LocalTransmit,  ///< Initiated by the local channel transmitter.
    Unknown,        ///< Driver could not determine the origin.
};

} // namespace nexigen::hw::can

namespace nexigen::core {

/// @brief Vocabulary table for `CanMessageOrigin`.
template <> struct EnumTraits<nexigen::hw::can::CanMessageOrigin> {
    /// @brief One value/name row.
    struct Entry {
        nexigen::hw::can::CanMessageOrigin value; ///< Enumerator.
        std::string_view name;                    ///< Canonical name.
    };
    /// @brief Canonical table.
    static constexpr std::array<Entry, 3> entries{{
        {nexigen::hw::can::CanMessageOrigin::ExternalDevice, "ExternalDevice"},
        {nexigen::hw::can::CanMessageOrigin::LocalTransmit, "LocalTransmit"},
        {nexigen::hw::can::CanMessageOrigin::Unknown, "Unknown"},
    }};
};

} // namespace nexigen::core

namespace nexigen::hw::can {

/// @brief Canonical name of a message origin.
/// @param origin Origin to render.
/// @return Canonical name or `Unknown`.
[[nodiscard]] constexpr std::string_view to_string(CanMessageOrigin origin) noexcept {
    return core::enum_name(origin);
}

/// @brief Parse a canonical message-origin name.
/// @param name Candidate name.
/// @param out Destination, unchanged on a miss.
/// @return `true` when a name matched.
[[nodiscard]] constexpr bool from_string(std::string_view name, CanMessageOrigin& out) noexcept {
    return core::enum_value(name, out);
}

/// @brief Write a message origin as JSON.
/// @param j Destination.
/// @param origin Origin to serialize.
inline void to_json(nlohmann::json& j, const CanMessageOrigin origin) {
    core::mandate::enum_to_json(j, origin);
}

/// @brief Read a message origin from JSON without throwing.
/// @param j Source.
/// @param origin Destination, unchanged on failure.
inline void from_json(const nlohmann::json& j, CanMessageOrigin& origin) noexcept {
    core::mandate::enum_from_json(j, origin);
}

} // namespace nexigen::hw::can

/// @brief `std::formatter` for `CanMessageOrigin`.
template <>
struct std::formatter<nexigen::hw::can::CanMessageOrigin> : std::formatter<std::string_view> {
    /// @brief Format the origin through its canonical name.
    /// @tparam Ctx Format context.
    /// @param origin Origin to render.
    /// @param ctx Context.
    /// @return Iterator past the text.
    template <class Ctx>
    auto format(const nexigen::hw::can::CanMessageOrigin origin, Ctx& ctx) const {
        return std::formatter<std::string_view>::format(nexigen::hw::can::to_string(origin), ctx);
    }
};
